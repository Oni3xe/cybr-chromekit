#!/usr/bin/env python3
"""Generate an app's chromekit token files from chromekit's tokens/tokens.json.

tokens/tokens.json is the approved tokens file, copied unmodified from the design vault.
Each consuming repo pins the tokens version it is on in its own `chromekit.version` (deprecated
fallback: `cybrcore.version`); the generator refuses a tokens file of another version or one
that is not approved.

Run from the consuming repo's root (the directory holding chromekit.json):

    python3 chromekit/tools/gen_tokens.py          # write the generated files
    python3 chromekit/tools/gen_tokens.py --check  # CI: fail if a generated file differs from its source

Options: --config PATH (default ./chromekit.json); --root DIR (default: the config's directory).

chromekit.json, "tokens" section (paths relative to the repo root):

    "tokens": {
      "kotlin": "app/src/main/java/com/example/app/chromekit/Tokens.kt",  # required
      "package": "com.example.app.chromekit",                             # required
      "colorType": "long",      # "long" (ARGB Long, Compose apps) or "int" (ARGB Int, Views apps)
      "hex": false,             # also emit Tokens.Hex (colours as "#RRGGBB" strings)
      "xml": null,              # or a res/values path: cybr_* <color> and <dimen> resources (e.g. chromekit_tokens.xml)
      "themes": null,           # or a Kotlin path: the theme palettes from tokens/themes.json (chromekit only)
      "exceptions": null        # or {"from": "cybr-map", "prefix": "map.", "object": "MapException",
                                #      "doc": "..."}: an app's named exceptions from tokens.json
    }
"""
import argparse
import hashlib
import json
import os
import re
import sys
from pathlib import Path

# Not resolve(): keep the path as the consumer sees it (chromekit/...), even through a symlink.
SELF = Path(os.path.abspath(__file__))
KIT = SELF.parents[1]
TOKENS = KIT / "tokens" / "tokens.json"
THEMES = KIT / "tokens" / "themes.json"


def read_pin(root: Path) -> tuple:
    """Prefer chromekit.version; fall back to the deprecated cybrcore.version alias."""
    new = root / "chromekit.version"
    old = root / "cybrcore.version"
    if new.is_file():
        return new.read_text().strip(), "chromekit.version"
    if old.is_file():
        return old.read_text().strip(), "cybrcore.version"
    raise SystemExit("missing chromekit.version (deprecated fallback: cybrcore.version)")


def const_name(key: str) -> str:
    return re.sub(r"[^A-Za-z0-9]+", "_", re.sub(r"([a-z])([A-Z])", r"\1_\2", key)).upper()


def res_name(key: str) -> str:
    return "cybr_" + re.sub(r"[^A-Za-z0-9]+", "_", key).lower()


def argb(hex_: str) -> str:
    h = hex_.lstrip("#").upper()
    if len(h) == 6:
        h = "FF" + h
    if len(h) != 8 or any(c not in "0123456789ABCDEF" for c in h):
        raise SystemExit(f"bad colour {hex_!r}")
    return h


def num(v) -> str:
    return f"{float(v)}f"


def rel(path: Path, root: Path) -> str:
    return Path(os.path.relpath(path, root)).as_posix()


def generate(root: Path, cfg: dict) -> dict:
    raw = TOKENS.read_bytes()
    t = json.loads(raw)
    pin, pin_file = read_pin(root)
    if t.get("version") != pin:
        raise SystemExit(f"{rel(TOKENS, root)} is version {t.get('version')}, but {pin_file} pins {pin}")
    if t.get("status") != "approved":
        raise SystemExit(f"{rel(TOKENS, root)} is not an approved version")
    sha = hashlib.sha256(raw).hexdigest()
    tool = rel(SELF, root)
    head = f"GENERATED by {tool} from {rel(TOKENS, root)} (chromekit {pin}, sha256 {sha[:16]}). Do not edit."

    long = cfg.get("colorType", "long") == "long"
    if cfg.get("colorType", "long") not in ("long", "int"):
        raise SystemExit("tokens.colorType must be \"long\" or \"int\"")
    ctype = "Long" if long else "Int"

    def colour(v: str) -> str:
        return f"0x{argb(v)}L" if long else f"0x{argb(v)}.toInt()"

    colors = t["color"]
    k = [f"// {head}", f"package {cfg['package']}", "",
         f"/** chromekit design tokens. Regenerate with `python3 {tool}`. */",
         "@Suppress(\"unused\")", "object Tokens {", f"    const val VERSION = \"{pin}\"", ""]
    k.append(f"    /** Colours as ARGB {ctype.lower()}s. */")
    k.append("    object Color {")
    for key, v in colors.items():
        k.append(f"        const val {const_name(key)}: {ctype} = {colour(v)}")
    k.append("    }")
    k.append("")
    if cfg.get("hex"):
        k.append("    /** Colours as hex strings, for user-pickable defaults stored as text. */")
        k.append("    object Hex {")
        for key, v in colors.items():
            k.append(f"        const val {const_name(key)} = \"{v.upper()}\"")
        k.append("    }")
        k.append("")
    k.append("    /** Colour roles. */")
    k.append("    object Role {")
    for key, v in t["role"].items():
        k.append(f"        const val {const_name(key)}: {ctype} = Color.{const_name(v)}")
    k.append("    }")
    k.append("")
    ex = cfg.get("exceptions")
    if ex:
        k.append(f"    /** {ex['doc']} */")
        k.append(f"    object {ex['object']} {{")
        for key, v in t["exceptions"][ex["from"]].items():
            if not key.startswith(ex["prefix"]):
                continue
            k.append(f"        const val {const_name(key[len(ex['prefix']):])}: {ctype} = {colour(v)}")
        k.append("    }")
        k.append("")
    m = t["motion"]
    k.append("    object Motion {")
    for key in ("pressLatchMs", "pressStepOffMs", "panelOpenMs", "panelCloseMs", "cursorBlinkMs", "scanBarSweepMs", "toastMs"):
        k.append(f"        const val {const_name(key)}: Long = {int(m[key])}L")
    k.append("    }")
    k.append("")
    g = t["state"]["pressed"]["glow"]
    k.append("    /** Pressed-state glow: strokes drawn behind the frame, never shadow(). */")
    k.append("    object Glow {")
    k.append("        val STROKES_DP = floatArrayOf(" + ", ".join(num(x) for x in g["strokesDp"]) + ")")
    k.append("        val ALPHA = floatArrayOf(" + ", ".join(num(x) for x in g["alpha"]) + ")")
    k.append("    }")
    k.append("")
    s = t["space"]
    k.append("    object Space {")
    for v in s["scaleDp"]:
        k.append(f"        const val S{int(v)}: Int = {int(v)}")
    k.append(f"        const val GUTTER: Int = {int(s['gutterDp'])}")
    k.append(f"        const val PANEL_PADDING: Int = {int(s['panelPaddingDp'])}")
    k.append("    }")
    k.append("")
    sh = t["shape"]
    k.append("    object Shape {")
    k.append(f"        const val CORNER_RADIUS_DP: Float = {num(sh['cornerRadiusDp'])}")
    k.append(f"        const val BORDER_DP: Float = {num(sh['borderDp'])}")
    k.append(f"        const val FOCUS_RING_DP: Float = {num(sh['focusRingDp'])}")
    k.append(f"        const val CHAMFER_DP: Float = {num(sh['chamfer']['sizeDp'])}")
    k.append("        val DISABLED_DASH_DP = floatArrayOf(" + ", ".join(num(x) for x in t['state']['disabled']['dashDp']) + ")")
    k.append("    }")
    k.append("")
    k.append("    /** Type scale: size, tracking and line height in sp, weight 100-900. */")
    k.append("    object Type {")
    for key, v in t["type"]["scaleSp"].items():
        n = const_name(key)
        k.append(f"        const val {n}_SP: Float = {num(v['size'])}")
        if "weight" in v:
            k.append(f"        const val {n}_WEIGHT: Int = {int(v['weight'])}")
        k.append(f"        const val {n}_TRACKING_SP: Float = {num(v.get('tracking', 0))}")
        if "lineHeight" in v:
            k.append(f"        const val {n}_LINE_HEIGHT_SP: Float = {num(v['lineHeight'])}")
    k.append("    }")
    k.append("")
    L = t["layout"]
    b, a, r, mp, hd, tb = L["button"], L["actionBar"], L["listRow"], L["menuPanel"], L["header"], L["tabs"]
    k.append("    object Layout {")
    k.append(f"        const val HEADER_HEIGHT_DP: Int = {int(hd['heightDp'])}")
    k.append(f"        const val BUTTON_PADDING_H_DP: Int = {int(b['paddingHorizontalDp'])}")
    k.append(f"        const val BUTTON_VISUAL_HEIGHT_DP: Int = {int(b['visualHeightDp'])}")
    k.append(f"        const val BUTTON_TOUCH_HEIGHT_DP: Int = {int(b['touchHeightDp'])}")
    k.append(f"        const val ACTION_SLOT_DP: Int = {int(a['actionSlotDp'])}")
    k.append(f"        const val MENU_SLOT_DP: Int = {int(a['menuSlotDp'])}")
    k.append(f"        const val ACTION_GAP_DP: Int = {int(a['gapDp'])}")
    k.append(f"        const val ACTION_GUTTER_DP: Int = {int(a['gutterDp'])}")
    k.append(f"        const val TAB_WIDTH_DP: Int = {int(tb['widthDp'])}")
    k.append(f"        const val TAB_GAP_DP: Int = {int(tb['gapDp'])}")
    k.append(f"        const val TAB_VISUAL_HEIGHT_DP: Int = {int(tb['visualHeightDp'])}")
    k.append(f"        const val TAB_TOUCH_HEIGHT_DP: Int = {int(tb['touchHeightDp'])}")
    k.append(f"        const val TAB_PADDING_H_MIN_DP: Int = {int(tb['paddingHorizontalMinDp'])}")
    k.append(f"        const val LIST_ROW_MIN_HEIGHT_DP: Int = {int(r['minHeightDp'])}")
    k.append(f"        const val MENU_MIN_WIDTH_DP: Int = {int(mp['minWidthDp'])}")
    k.append("    }")
    k.append("}")
    out = {root / cfg["kotlin"]: "\n".join(k) + "\n"}
    if cfg.get("themes"):
        out[root / cfg["themes"]] = gen_themes(root, cfg, colors, t["role"], tool, pin)

    if cfg.get("xml"):
        x = ['<?xml version="1.0" encoding="utf-8"?>', f"<!-- {head} -->", "<resources>"]
        for key, v in colors.items():
            x.append(f'    <color name="{res_name(key)}">#{argb(v)}</color>')
        x.append(f'    <dimen name="cybr_border">{num(sh["borderDp"])[:-1]}dp</dimen>')
        x.append(f'    <dimen name="cybr_chamfer">{num(sh["chamfer"]["sizeDp"])[:-1]}dp</dimen>')
        x.append(f'    <dimen name="cybr_gutter">{int(s["gutterDp"])}dp</dimen>')
        x.append("</resources>")
        out[root / cfg["xml"]] = "\n".join(x) + "\n"
    return out


# CybrColors fields, in constructor order, and the tokens.json key each one reads.
THEME_FIELDS = [("bg", "bg"), ("surface1", "surface.1"), ("surface2", "surface.2"), ("scrim", "scrim"),
                ("redBright", "red.bright"), ("red", "red"), ("redDim", "red.dim"), ("redDeep", "red.deep"),
                ("cyanBright", "cyan.bright"), ("cyan", "cyan"), ("cyanDim", "cyan.dim"), ("cyanDeep", "cyan.deep"),
                ("text", "text"), ("textMuted", "text.muted"), ("disabled", "disabled"),
                ("green", "green"), ("gold", "gold"), ("error", "error"), ("warning", "warning")]


def resolve_themes(colors: dict, roles: dict) -> tuple:
    """Return (themes.json document, [(theme, {key: hex})]) with every theme fully resolved.

    A theme overrides tokens.json colour keys; anything it leaves out comes from tokens.json.
    "warning" defaults to the tokens' warning role colour (the Red theme's red)."""
    doc = json.loads(THEMES.read_text())
    base = dict(colors)
    base["warning"] = colors[roles["warning"]]
    seen, out = set(), []
    for th in doc["themes"]:
        tid = th["id"]
        if not re.fullmatch(r"[a-z][a-z0-9_]*", tid) or tid in seen:
            raise SystemExit(f"themes.json: bad or duplicate theme id {tid!r}")
        seen.add(tid)
        unknown = set(th.get("colors", {})) - set(base)
        if unknown:
            raise SystemExit(f"themes.json: theme {tid} sets unknown colour keys {sorted(unknown)}")
        pal = {**base, **th.get("colors", {})}
        for key, v in pal.items():
            if argb(v)[2:] == "FFFFFF":
                raise SystemExit(f"themes.json: theme {tid} {key} is white; chromekit never uses white")
        out.append((th, pal))
    if doc.get("default") not in seen:
        raise SystemExit("themes.json: \"default\" must name a theme")
    first = doc["themes"][0]
    if first["id"] != "red" or first.get("colors"):
        raise SystemExit("themes.json: the first theme must be \"red\" with no overrides (identical to tokens.json)")
    return doc, out


def gen_themes(root: Path, cfg: dict, colors: dict, roles: dict, tool: str, pin: str) -> str:
    doc, themes = resolve_themes(colors, roles)
    sha = hashlib.sha256(THEMES.read_bytes()).hexdigest()
    pkg = cfg.get("themesPackage", cfg["package"] + ".theme")
    k = [f"// GENERATED by {tool} from {rel(THEMES, root)} (chromekit {pin}, sha256 {sha[:16]}). Do not edit.",
         f"package {pkg}", "",
         "/** Theme palettes as ARGB longs, in picker order. Edit tokens/themes.json, then regenerate. */",
         "internal object GeneratedThemes {",
         f"    const val DEFAULT_ID = \"{doc['default']}\"", "",
         "    val ALL: List<ThemePalette> = listOf("]
    for th, pal in themes:
        k.append(f"        ThemePalette(")
        k.append(f"            id = \"{th['id']}\", label = \"{th['label']}\", lowContrast = {str(bool(th.get('lowContrast'))).lower()},")
        for field, key in THEME_FIELDS:
            k.append(f"            {field} = 0x{argb(pal[key])}L,")
        k.append("        ),")
    k += ["    )", "}"]
    return "\n".join(k) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if a generated file is out of date")
    ap.add_argument("--config", default="chromekit.json")
    ap.add_argument("--root", default=None)
    args = ap.parse_args()
    config = Path(os.path.abspath(args.config))
    root = Path(os.path.abspath(args.root)) if args.root else config.parent
    cfg = json.loads(config.read_text())["tokens"]
    stale = []
    for path, text in generate(root, cfg).items():
        if args.check:
            if not path.exists() or path.read_text() != text:
                stale.append(rel(path, root))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
            print(f"wrote {rel(path, root)}")
    if stale:
        print(f"chromekit tokens are out of sync with {rel(TOKENS, root)}: " + ", ".join(stale))
        print(f"Run: python3 {rel(SELF, root)}")
        sys.exit(1)
    if args.check:
        print("chromekit tokens in sync")


if __name__ == "__main__":
    main()
